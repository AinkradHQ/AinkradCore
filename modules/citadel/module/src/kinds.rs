#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_name_is_the_modules_own_and_unique() {
        let mut seen = std::collections::HashSet::new();
        for name in EVENT_KINDS.iter().chain(AUDIT_ACTIONS) {
            assert!(name.starts_with("citadel."), "{name}");
            assert!(seen.insert(*name), "{name} twice");
        }
    }
}
